#!/usr/bin/env bash
#
# Copies legacy data/web/sogo-auth.php, data/web/inc/vars.inc.php and data/web/inc/sessions.inc.php
# of an upstream mailcow-dockerized tag unmodified into tests/fixtures/legacy/sogo-auth/<tag>/
# (keeping the inc/ sub-directory), with an ORIGIN file naming the tag and the SHA-256 of each file
# (feature 005 research R3). tests/Feature/Webmail/SogoAuthCompatibilityTest runs the copy under a
# throw-away php-fpm pool to prove that the webmail hand-off's legacy session is honoured.
#
#   scripts/legacy/extract-sogo-auth.sh 2026-09a
#
# MAILCOW_REPO is a mailcow-dockerized checkout (default ./source_code). Only tags are accepted.

set -euo pipefail

TAG="${1:-}"
if [[ -z "$TAG" ]]; then
    echo "usage: $0 <upstream tag>" >&2
    exit 64
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
MAILCOW_REPO="${MAILCOW_REPO:-$ROOT/source_code}"
OUT="$ROOT/tests/fixtures/legacy/sogo-auth/$TAG"

if ! git -C "$MAILCOW_REPO" rev-parse -q --verify "refs/tags/$TAG" >/dev/null; then
    echo "error: '$TAG' is not a tag of $MAILCOW_REPO (branches and commits are refused)" >&2
    exit 65
fi

rm -rf "$OUT"
mkdir -p "$OUT/inc"

{
    echo "Legacy webmail single sign-on check of mailcow-dockerized, copied unmodified."
    echo
    echo "Source: data/web at tag $TAG"
    echo "Generated by scripts/legacy/extract-sogo-auth.sh $TAG. Do not edit: regenerate instead."
    echo "Distributed in mailcow-dockerized under the GNU General Public License, version 3."
    echo
    echo "SHA-256 of each file:"
} >"$OUT/ORIGIN"

for rel in sogo-auth.php inc/vars.inc.php inc/sessions.inc.php; do
    git -C "$MAILCOW_REPO" show "$TAG:data/web/$rel" >"$OUT/$rel"
    echo "$(sha256sum "$OUT/$rel" | cut -d' ' -f1)  $rel" >>"$OUT/ORIGIN"
done

echo "wrote $OUT ($TAG)" >&2
