#!/usr/bin/env bash
#
# Regenerates tests/fixtures/schema/<tag>.sql from an upstream mailcow-dockerized tag (research R2).
#
#   scripts/schema/generate-fixture.sh 2026-09a
#
# MAILCOW_REPO is a mailcow-dockerized checkout (default ./source_code). Only tags are accepted:
# supported releases are upstream releases, never fork branches. Runs on the host and needs Docker.
#
#   1. Reads init_db.inc.php, vars.inc.php, docker-compose.yml and the MariaDB my.cnf of the tag
#      with `git show`, and takes the mysql-mailcow and php-fpm-mailcow images from that
#      docker-compose.yml.
#   2. Starts the tag's MariaDB on a throwaway Docker network.
#   3. Runs scripts/schema/init-db-harness.php (upstream's unmodified init_db_schema()) in the
#      tag's php-fpm-mailcow image.
#   4. Dumps the schema (no data, plus the versions row), strips DEFINER= and AUTO_INCREMENT=.
#   5. Writes a header with the tag, the db_version and the SHA-256 of init_db.inc.php.

set -euo pipefail

TAG="${1:-}"
if [[ -z "$TAG" ]]; then
    echo "usage: $0 <upstream tag>" >&2
    exit 64
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
MAILCOW_REPO="${MAILCOW_REPO:-$ROOT/source_code}"

if ! git -C "$MAILCOW_REPO" rev-parse -q --verify "refs/tags/$TAG" >/dev/null; then
    echo "error: '$TAG' is not a tag of $MAILCOW_REPO (branches and commits are refused)" >&2
    exit 65
fi

WORK="$(mktemp -d)"
SUFFIX="$$-$RANDOM"
NET="restv2-fixture-net-$SUFFIX"
DB="restv2-fixture-db-$SUFFIX"
ROOTPW="fixture-root"

cleanup() {
    docker rm -f "$DB" >/dev/null 2>&1 || true
    docker network rm "$NET" >/dev/null 2>&1 || true
    rm -rf "$WORK"
}
trap cleanup EXIT

show() { git -C "$MAILCOW_REPO" show "$TAG:$1"; }

show data/web/inc/init_db.inc.php >"$WORK/init_db.inc.php"
show data/web/inc/vars.inc.php >"$WORK/vars.inc.php"
show docker-compose.yml >"$WORK/docker-compose.yml"
show data/conf/mysql/my.cnf >"$WORK/my.cnf" 2>/dev/null || : >"$WORK/my.cnf"
chmod 0644 "$WORK"/*
chmod 0755 "$WORK"

service_image() {
    awk -v svc="$1" '
        $0 ~ "^    " svc ":[[:space:]]*$" { inside = 1; next }
        inside && /^    [^[:space:]]/ { exit }
        inside && $1 == "image:" { print $2; exit }
    ' "$WORK/docker-compose.yml"
}

MYSQL_IMAGE="$(service_image mysql-mailcow)"
PHP_IMAGE="$(service_image php-fpm-mailcow)"
if [[ -z "$MYSQL_IMAGE" || -z "$PHP_IMAGE" ]]; then
    echo "error: mysql-mailcow or php-fpm-mailcow image not found in $TAG docker-compose.yml" >&2
    exit 1
fi
SHA256="$(sha256sum "$WORK/init_db.inc.php" | cut -d' ' -f1)"
echo "tag $TAG: $MYSQL_IMAGE, $PHP_IMAGE, init_db.inc.php sha256 $SHA256" >&2

docker network create "$NET" >/dev/null
docker run -d --name "$DB" --network "$NET" \
    -e MYSQL_ROOT_PASSWORD="$ROOTPW" \
    -e MYSQL_DATABASE=mailcow -e MYSQL_USER=mailcow -e MYSQL_PASSWORD=mailcow \
    -e MYSQL_INITDB_SKIP_TZINFO=1 -e TZ=UTC \
    -v "$WORK/my.cnf:/etc/mysql/conf.d/mailcow.cnf:ro" \
    "$MYSQL_IMAGE" >/dev/null

# The image's init phase runs a temporary server without networking; a TCP connection only
# succeeds once the real server is up.
for _ in $(seq 1 90); do
    if docker exec "$DB" mariadb --protocol=tcp -h127.0.0.1 -umailcow -pmailcow -e 'SELECT 1' mailcow >/dev/null 2>&1; then
        READY=1
        break
    fi
    sleep 1
done
if [[ -z "${READY:-}" ]]; then
    echo "error: $MYSQL_IMAGE did not become ready" >&2
    docker logs "$DB" >&2 || true
    exit 1
fi

docker run --rm --network "$NET" --entrypoint php \
    -e HARNESS_SRC=/src -e DBHOST="$DB" -e DBNAME=mailcow -e DBUSER=mailcow -e DBPASS=mailcow \
    -v "$WORK:/src:ro" \
    -v "$ROOT/scripts/schema/init-db-harness.php:/harness/init-db-harness.php:ro" \
    "$PHP_IMAGE" /harness/init-db-harness.php >"$WORK/harness.out"

DB_VERSION="$(sed -n 's/^db_version //p' "$WORK/harness.out")"
if [[ -z "$DB_VERSION" ]]; then
    echo "error: the harness reported no db_version" >&2
    cat "$WORK/harness.out" >&2
    exit 1
fi

DUMP=(docker exec "$DB" mariadb-dump -uroot "-p$ROOTPW" --skip-comments --skip-add-drop-table --skip-dump-date --skip-tz-utc)
"${DUMP[@]}" --no-data --routines --triggers mailcow >"$WORK/schema.sql"
# The versions row only. Its `created` value is replaced by NOW() so that the file is
# deterministic; the column default is NOW() anyway.
"${DUMP[@]}" --no-create-info --complete-insert --skip-extended-insert mailcow versions \
    | sed -E "s/'[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}:[0-9]{2}'/NOW()/g" >"$WORK/versions.sql"

OUT="$ROOT/tests/fixtures/schema/$TAG.sql"
mkdir -p "$(dirname "$OUT")"
{
    echo "-- mailcow-dockerized upstream schema fixture"
    echo "-- tag $TAG"
    echo "-- db_version $DB_VERSION"
    echo "-- init_db.inc.php sha256 $SHA256"
    echo "-- images $MYSQL_IMAGE, $PHP_IMAGE"
    echo "-- Generated by scripts/schema/generate-fixture.sh $TAG with upstream's own init_db_schema()."
    echo "-- Do not edit: regenerate instead. Definer clauses and auto-increment counters are stripped."
    echo
    cat "$WORK/schema.sql"
    echo
    cat "$WORK/versions.sql"
} | sed -E \
    -e 's/DEFINER=`[^`]*`@`[^`]*` ?//g' \
    -e 's/ AUTO_INCREMENT=[0-9]+//g' >"$OUT"

if grep -v '^--' "$OUT" | grep -q 'DEFINER='; then
    echo "error: DEFINER= left in $OUT" >&2
    exit 1
fi

echo "wrote $OUT (db_version $DB_VERSION)" >&2
