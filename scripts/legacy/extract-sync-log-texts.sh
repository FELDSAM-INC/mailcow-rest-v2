#!/usr/bin/env bash
#
# Lists the scheduled-job log texts of legacy's identity provider synchronisation jobs
# (data/conf/phpfpm/crons/keycloak-sync.php and ldap-sync.php) of an upstream mailcow-dockerized
# tag, for the synchronisation status of feature 012 (research R12). Every logMsg(priority, message)
# call becomes one entry with its task, its priority, the literal text the message starts with
# (`prefix`, up to the first interpolated value) and whether the whole message is that literal
# (`exact`). App\Services\IdentityProvider\SynchronisationLogParser must classify every entry; its
# test reads the output, so a release that changes the texts fails the parity suite.
#
#   scripts/legacy/extract-sync-log-texts.sh 2026-09a
#
# Writes tests/fixtures/cron-log/<tag>-messages.json. MAILCOW_REPO is a mailcow-dockerized
# checkout (default ./source_code). Only tags are accepted. Needs jq.

set -euo pipefail

TAG="${1:-}"
if [[ -z "$TAG" ]]; then
    echo "usage: $0 <upstream tag>" >&2
    exit 64
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
MAILCOW_REPO="${MAILCOW_REPO:-$ROOT/source_code}"

if ! git -C "$MAILCOW_REPO" rev-parse -q --verify "refs/tags/$TAG" >/dev/null; then
    echo "error: '$TAG' is not a tag of $MAILCOW_REPO (branches and commits are refused)" >&2
    exit 65
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

entries="$WORK/entries.jsonl"
: >"$entries"
sources="{}"

for job in keycloak-sync ldap-sync; do
    path="data/conf/phpfpm/crons/$job.php"
    git -C "$MAILCOW_REPO" show "$TAG:$path" | tr -d '\r' >"$WORK/$job.php"
    sha="$(sha256sum "$WORK/$job.php" | cut -d' ' -f1)"
    sources="$(jq -c --arg p "$path" --arg s "$sha" '. + {($p): $s}' <<<"$sources")"

    # The task name is the default of logMsg()'s third parameter.
    task="$(sed -nE 's/^function logMsg\(\$priority, \$message, \$task = "([^"]+)"\).*/\1/p' "$WORK/$job.php")"
    if [[ -z "$task" ]]; then
        echo "error: no logMsg() definition with a task name in $TAG:$path" >&2
        exit 1
    fi

    # Every call: line number, priority and the message expression (single line in these files).
    grep -nE '^[[:space:]]*logMsg\("[a-z]+", ' "$WORK/$job.php" | while IFS= read -r match; do
        line="${match%%:*}"
        call="${match#*:}"
        priority="$(sed -E 's/^[[:space:]]*logMsg\("([a-z]+)", .*/\1/' <<<"$call")"
        expression="$(sed -E 's/^[[:space:]]*logMsg\("[a-z]+", (.*)\);[[:space:]]*$/\1/' <<<"$call")"

        prefix=""
        exact=false
        if [[ "$expression" =~ ^\"([^\"]*)\"$ && "${BASH_REMATCH[1]}" != *'$'* ]]; then
            prefix="${BASH_REMATCH[1]}"
            exact=true
        elif [[ "$expression" =~ ^\"([^\"\$\{]*) ]]; then
            prefix="${BASH_REMATCH[1]}"
        fi

        jq -cn --arg task "$task" --arg priority "$priority" --arg prefix "$prefix" \
            --argjson exact "$exact" --arg source "$path" --argjson line "$line" \
            --arg expression "$expression" \
            '{task: $task, priority: $priority, prefix: $prefix, exact: $exact, source: $source, line: $line, expression: $expression}' \
            >>"$entries"
    done
done

if [[ ! -s "$entries" ]]; then
    echo "error: no logMsg() calls found in $TAG" >&2
    exit 1
fi

OUT="$ROOT/tests/fixtures/cron-log/$TAG-messages.json"
mkdir -p "$(dirname "$OUT")"
jq -s --arg tag "$TAG" --argjson sources "$sources" \
    '{description: ("logMsg() calls of the identity provider synchronisation jobs of mailcow-dockerized " + $tag + ". Generated by scripts/legacy/extract-sync-log-texts.sh " + $tag + ". Do not edit: regenerate instead."), tag: $tag, sources: $sources, messages: .}' \
    "$entries" >"$OUT"

echo "wrote $OUT ($(wc -l <"$entries") messages)" >&2
