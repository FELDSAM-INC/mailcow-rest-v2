#!/usr/bin/env bash
#
# Copies legacy's sync-job validation of an upstream mailcow-dockerized tag into
# tests/fixtures/legacy/syncjob_validation.php (feature 008 research R20):
#
#  - legacy_syncjob_custom_params_ok(string $custom_params, array $whitelist): bool wraps the
#    "// validate custom params" block of mailbox('add', 'syncjob') (functions.mailbox.inc.php,
#    up to the line before `if (empty($subfolder2)) {`); its `return false` becomes the result;
#  - legacy_syncjob_is_valid_domain_name() is is_valid_domain_name() of functions.inc.php.
#
# The unit tests of App\Services\SyncJobs\CustomParametersValidator and App\Rules\SyncJobHostName
# compare the API's checks with these functions.
#
#   scripts/legacy/extract-syncjob-validation.sh 2026-09a
#
# MAILCOW_REPO is a mailcow-dockerized checkout (default ./source_code). Only tags are accepted.

set -euo pipefail

TAG="${1:-}"
if [[ -z "$TAG" ]]; then
    echo "usage: $0 <upstream tag>" >&2
    exit 64
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
MAILCOW_REPO="${MAILCOW_REPO:-$ROOT/source_code}"
MAILBOX_SOURCE="data/web/inc/functions.mailbox.inc.php"
FUNCTIONS_SOURCE="data/web/inc/functions.inc.php"

if ! git -C "$MAILCOW_REPO" rev-parse -q --verify "refs/tags/$TAG" >/dev/null; then
    echo "error: '$TAG' is not a tag of $MAILCOW_REPO (branches and commits are refused)" >&2
    exit 65
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

git -C "$MAILCOW_REPO" show "$TAG:$MAILBOX_SOURCE" >"$WORK/mailbox.raw.php"
git -C "$MAILCOW_REPO" show "$TAG:$FUNCTIONS_SOURCE" >"$WORK/functions.raw.php"
MAILBOX_SHA256="$(sha256sum "$WORK/mailbox.raw.php" | cut -d' ' -f1)"
FUNCTIONS_SHA256="$(sha256sum "$WORK/functions.raw.php" | cut -d' ' -f1)"
# The legacy files use CRLF line endings; the copies are normalised to LF.
tr -d '\r' <"$WORK/mailbox.raw.php" >"$WORK/mailbox.php"
tr -d '\r' <"$WORK/functions.raw.php" >"$WORK/functions.php"

# The first custom-parameter block (the add path), without the line that ends it.
awk '
    !found && /\/\/ validate custom params/ { found = 1; inside = 1 }
    inside && /if \(empty\(\$subfolder2\)\) \{/ { exit }
    inside { print }
' "$WORK/mailbox.php" >"$WORK/block.php"

if [[ ! -s "$WORK/block.php" ]] || ! grep -q 'IMAPSYNC_OPTIONS' "$WORK/block.php"; then
    echo "error: the custom-parameter block was not found in $TAG:$MAILBOX_SOURCE" >&2
    exit 1
fi

# A top-level function runs from "function <name>(" to the first "}" in column 0.
awk '
    /^function is_valid_domain_name\(/ { inside = 1 }
    inside { print }
    inside && /^}/ { exit }
' "$WORK/functions.php" >"$WORK/domain.php"

if ! grep -q '^function is_valid_domain_name(' "$WORK/domain.php"; then
    echo "error: is_valid_domain_name() not found in $TAG:$FUNCTIONS_SOURCE" >&2
    exit 1
fi

OUT="$ROOT/tests/fixtures/legacy/syncjob_validation.php"
mkdir -p "$(dirname "$OUT")"
{
    echo "<?php"
    echo
    echo "/*"
    echo " * Sync-job validation of mailcow-dockerized, wrapped for the feature 008 tests:"
    echo " *"
    echo " *  - legacy_syncjob_custom_params_ok(): the \"// validate custom params\" block of"
    echo " *    mailbox('add', 'syncjob'), verbatim, inside a closure whose \`return false\` is the result;"
    echo " *  - legacy_syncjob_is_valid_domain_name(): is_valid_domain_name(), renamed."
    echo " *"
    echo " * Source: $MAILBOX_SOURCE at tag $TAG"
    echo " * Source SHA-256: $MAILBOX_SHA256 (line endings normalised to LF)"
    echo " * Source: $FUNCTIONS_SOURCE at tag $TAG"
    echo " * Source SHA-256: $FUNCTIONS_SHA256 (line endings normalised to LF)"
    echo " * Generated by scripts/legacy/extract-syncjob-validation.sh $TAG. Do not edit: regenerate instead."
    echo " *"
    echo " * Copyright (c) The mailcow team and contributors."
    echo " * This program is free software: you can redistribute it and/or modify it under the terms of"
    echo " * the GNU General Public License as published by the Free Software Foundation, version 3."
    echo " * It is distributed WITHOUT ANY WARRANTY; see the GNU General Public License for details."
    echo " */"
    echo
    echo "function legacy_syncjob_custom_params_ok(string \$custom_params, array \$whitelist): bool"
    echo "{"
    echo "    \$GLOBALS['IMAPSYNC_OPTIONS']['whitelist'] = \$whitelist;"
    echo "    \$_SESSION['return'] = [];"
    echo "    // PHP 8 warns on \$param[0] for an empty option name; legacy runs with warnings hidden."
    echo "    set_error_handler(static fn (): bool => true);"
    echo
    echo "    try {"
    echo "        return (static function (string \$custom_params): bool {"
    echo "            \$_action = \$_type = \$_data_log = \$_attr = null;"
    echo
    cat "$WORK/block.php"
    echo
    echo "            return true;"
    echo "        })(\$custom_params);"
    echo "    } finally {"
    echo "        restore_error_handler();"
    echo "    }"
    echo "}"
    echo
    sed -E -e 's/\bis_valid_domain_name\b/legacy_syncjob_is_valid_domain_name/g' "$WORK/domain.php"
} >"$OUT"

echo "wrote $OUT ($TAG, sha256 $MAILBOX_SHA256 / $FUNCTIONS_SHA256)" >&2
