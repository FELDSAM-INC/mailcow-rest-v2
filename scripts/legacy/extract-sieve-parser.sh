#!/usr/bin/env bash
#
# Copies the legacy Sieve parser (data/web/inc/lib/sieve/, namespace Sieve) of an upstream
# mailcow-dockerized tag unmodified into resources/legacy/sieve/ (feature 005 research R13), with an
# ORIGIN file naming the tag and the SHA-256 of each file. Composer loads the copy through its
# classmap, and App\Support\Sieve\SieveValidator validates Sieve filters with it, so that the API
# accepts exactly the scripts legacy accepts.
#
#   scripts/legacy/extract-sieve-parser.sh 2026-09a
#
# MAILCOW_REPO is a mailcow-dockerized checkout (default ./source_code). Only tags are accepted.

set -euo pipefail

TAG="${1:-}"
if [[ -z "$TAG" ]]; then
    echo "usage: $0 <upstream tag>" >&2
    exit 64
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
MAILCOW_REPO="${MAILCOW_REPO:-$ROOT/source_code}"
SOURCE="data/web/inc/lib/sieve"
OUT="$ROOT/resources/legacy/sieve"

if ! git -C "$MAILCOW_REPO" rev-parse -q --verify "refs/tags/$TAG" >/dev/null; then
    echo "error: '$TAG' is not a tag of $MAILCOW_REPO (branches and commits are refused)" >&2
    exit 65
fi

FILES="$(git -C "$MAILCOW_REPO" ls-tree -r --name-only "$TAG" "$SOURCE/")"
if [[ -z "$FILES" ]]; then
    echo "error: $SOURCE not found in $TAG" >&2
    exit 1
fi

rm -rf "$OUT"
mkdir -p "$OUT"

{
    echo "Legacy Sieve parser of mailcow-dockerized, copied unmodified."
    echo
    echo "Source: $SOURCE/ at tag $TAG"
    echo "Generated by scripts/legacy/extract-sieve-parser.sh $TAG. Do not edit: regenerate instead."
    echo
    echo "These files are distributed in mailcow-dockerized under the GNU General Public License,"
    echo "version 3 (GPL-3.0), the licence of this project."
    echo
    echo "SHA-256 of each file:"
} >"$OUT/ORIGIN"

while IFS= read -r path; do
    rel="${path#"$SOURCE"/}"
    mkdir -p "$OUT/$(dirname "$rel")"
    git -C "$MAILCOW_REPO" show "$TAG:$path" >"$OUT/$rel"
    echo "$(sha256sum "$OUT/$rel" | cut -d' ' -f1)  $rel" >>"$OUT/ORIGIN"
done <<<"$FILES"

echo "wrote $OUT ($TAG)" >&2
