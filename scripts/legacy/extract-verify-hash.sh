#!/usr/bin/env bash
#
# Copies legacy verify_salted_hash() and verify_hash() of an upstream mailcow-dockerized tag into
# tests/fixtures/legacy/verify_hash.php, renamed legacy_verify_salted_hash() and
# legacy_verify_hash() (research R12). The test of App\Support\Hashing\LegacyPasswordVerifier
# asserts that the port and the legacy functions agree on every test vector.
#
#   scripts/legacy/extract-verify-hash.sh 2026-09a
#
# MAILCOW_REPO is a mailcow-dockerized checkout (default ./source_code). Only tags are accepted.

set -euo pipefail

TAG="${1:-}"
if [[ -z "$TAG" ]]; then
    echo "usage: $0 <upstream tag>" >&2
    exit 64
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
MAILCOW_REPO="${MAILCOW_REPO:-$ROOT/source_code}"
SOURCE="data/web/inc/functions.inc.php"

if ! git -C "$MAILCOW_REPO" rev-parse -q --verify "refs/tags/$TAG" >/dev/null; then
    echo "error: '$TAG' is not a tag of $MAILCOW_REPO (branches and commits are refused)" >&2
    exit 65
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

git -C "$MAILCOW_REPO" show "$TAG:$SOURCE" >"$WORK/functions.inc.php"
SHA256="$(sha256sum "$WORK/functions.inc.php" | cut -d' ' -f1)"

# A top-level function runs from "function <name>(" to the first "}" in column 0.
extract() {
    awk -v name="$1" '
        $0 ~ "^function " name "\\(" { inside = 1 }
        inside { print }
        inside && /^}/ { exit }
    ' "$WORK/functions.inc.php"
}

extract verify_salted_hash >"$WORK/functions.php"
extract verify_hash >>"$WORK/functions.php"

for fn in verify_salted_hash verify_hash; do
    if ! grep -q "^function $fn(" "$WORK/functions.php"; then
        echo "error: $fn() not found in $TAG:$SOURCE" >&2
        exit 1
    fi
done

OUT="$ROOT/tests/fixtures/legacy/verify_hash.php"
mkdir -p "$(dirname "$OUT")"
{
    echo "<?php"
    echo
    echo "/*"
    echo " * verify_salted_hash() and verify_hash() of mailcow-dockerized, renamed with a legacy_ prefix."
    echo " *"
    echo " * Source: $SOURCE at tag $TAG"
    echo " * Source SHA-256: $SHA256"
    echo " * Generated by scripts/legacy/extract-verify-hash.sh $TAG. Do not edit: regenerate instead."
    echo " *"
    echo " * Copyright (c) The mailcow team and contributors."
    echo " * This program is free software: you can redistribute it and/or modify it under the terms of"
    echo " * the GNU General Public License as published by the Free Software Foundation, version 3."
    echo " * It is distributed WITHOUT ANY WARRANTY; see the GNU General Public License for details."
    echo " */"
    echo
    sed -E -e 's/\bverify_salted_hash\b/legacy_verify_salted_hash/g' \
        -e 's/\bverify_hash\b/legacy_verify_hash/g' "$WORK/functions.php"
} >"$OUT"

echo "wrote $OUT ($TAG, sha256 $SHA256)" >&2
