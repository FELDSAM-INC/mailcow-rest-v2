#!/usr/bin/env bash
#
# Generates a DKIM key pair with legacy dkim('add')'s own key-handling code, run in the PHP image of
# mailcow's php-fpm container, and writes tests/fixtures/legacy/dkim/generated-2048.pem (the private
# key exactly as legacy stores it in DKIM_PRIV_KEYS) and generated-2048.pub (the public key text of
# DKIM_PUB_KEYS). Feature 010 T007 (research R5, R26): the tests compare the API's derivation with
# legacy's byte for byte.
#
#   scripts/legacy/extract-dkim-keygen.sh 2026-09a
#
# The key-handling lines below are legacy's verbatim; the script refuses to run when any of them is
# no longer present in the tag's functions.dkim.inc.php. MAILCOW_REPO is a mailcow-dockerized
# checkout (default ./source_code), PHPFPM_IMAGE the php-fpm-mailcow image of the tag.

set -euo pipefail

TAG="${1:-}"
if [[ -z "$TAG" ]]; then
    echo "usage: $0 <upstream tag>" >&2
    exit 64
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
MAILCOW_REPO="${MAILCOW_REPO:-$ROOT/source_code}"
PHPFPM_IMAGE="${PHPFPM_IMAGE:-ghcr.io/mailcow/phpfpm:8.2.29-3}"
SOURCE="data/web/inc/functions.dkim.inc.php"

if ! git -C "$MAILCOW_REPO" rev-parse -q --verify "refs/tags/$TAG" >/dev/null; then
    echo "error: '$TAG' is not a tag of $MAILCOW_REPO (branches and commits are refused)" >&2
    exit 65
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
git -C "$MAILCOW_REPO" show "$TAG:$SOURCE" | tr -d '\r' >"$WORK/functions.dkim.inc.php"
SHA256="$(git -C "$MAILCOW_REPO" show "$TAG:$SOURCE" | sha256sum | cut -d' ' -f1)"

# Legacy's key handling in dkim('add'), verbatim.
LINES=(
    '"digest_alg" => "sha256",'
    '"private_key_bits" => $key_length,'
    '"private_key_type" => OPENSSL_KEYTYPE_RSA,'
    'if ($keypair_ressource = openssl_pkey_new($config)) {'
    '$key_details = openssl_pkey_get_details($keypair_ressource);'
    '$pubKey = implode(array_slice('
    'explode(PHP_EOL, $key_details['"'"'key'"'"'])'
    'openssl_pkey_export($keypair_ressource, $privKey);'
    "\$redis->hSet('DKIM_PRIV_KEYS', \$dkim_selector . '.' . \$domain, trim(\$privKey));"
)
for line in "${LINES[@]}"; do
    if ! grep -qF -- "$line" "$WORK/functions.dkim.inc.php"; then
        echo "error: legacy line not found in $TAG:$SOURCE: $line" >&2
        exit 1
    fi
done

cat >"$WORK/keygen.php" <<'PHP'
<?php
$key_length = 2048;
$config = array(
  "digest_alg" => "sha256",
  "private_key_bits" => $key_length,
  "private_key_type" => OPENSSL_KEYTYPE_RSA,
);
if ($keypair_ressource = openssl_pkey_new($config)) {
  $key_details = openssl_pkey_get_details($keypair_ressource);
  $pubKey = implode(array_slice(
    array_filter(
      explode(PHP_EOL, $key_details['key'])
    ), 1, -1)
  );
  openssl_pkey_export($keypair_ressource, $privKey);
  file_put_contents('/work/generated-2048.pem', trim($privKey));
  file_put_contents('/work/generated-2048.pub', $pubKey);
}
PHP

docker run --rm --user "$(id -u):$(id -g)" --entrypoint php -v "$WORK:/work" "$PHPFPM_IMAGE" /work/keygen.php
PHP_VERSION="$(docker run --rm --entrypoint php "$PHPFPM_IMAGE" -r 'echo PHP_VERSION, " / ", OPENSSL_VERSION_TEXT;')"

OUT="$ROOT/tests/fixtures/legacy/dkim"
mkdir -p "$OUT"
cp "$WORK/generated-2048.pem" "$WORK/generated-2048.pub" "$OUT/"
cat >"$OUT/README.md" <<MD
# Legacy DKIM key fixtures

Generated by \`scripts/legacy/extract-dkim-keygen.sh $TAG\` with the key-handling code of legacy
\`dkim('add')\` (\`$SOURCE\` at tag \`$TAG\`, SHA-256 \`$SHA256\`), run in \`$PHPFPM_IMAGE\`
($PHP_VERSION).

- \`generated-2048.pem\`: the private key as legacy stores it in \`DKIM_PRIV_KEYS\` (\`trim(\$privKey)\`).
- \`generated-2048.pub\`: the public key text legacy stores in \`DKIM_PUB_KEYS\`.

These keys protect nothing. The legacy code is Copyright (c) the mailcow team and contributors,
GPL-3.0.
MD
echo "wrote $OUT ($TAG, sha256 $SHA256)" >&2
